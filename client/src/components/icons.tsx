export function CategoryIconRenderer({ iconName, size = 28, class: className = '' }: { iconName: string; size?: number; class?: string }) {
  switch (iconName) {
    case 'zap':
      return <ZapIcon size={size} class={className} />;
    case 'droplet':
      return <DropletIcon size={size} class={className} />;
    case 'tv':
      return <TvIcon size={size} class={className} />;
    case 'wind':
      return <WindIcon size={size} class={className} />;
    case 'tool':
      return <ToolIcon size={size} class={className} />;
    default:
      return <ZapIcon size={size} class={className} />;
  }
}

